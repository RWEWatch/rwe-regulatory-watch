"""Report assembly: AI disclosure, coverage tables, fallback digest, HTML rendering."""
from __future__ import annotations

from collections import Counter, defaultdict

import markdown as md

REGION_ORDER = ["Watchlist", "International", "Europe", "Americas", "Asia-Pacific",
                "Africa & Middle East", "Publications"]
STATUS_LABEL = {
    "ok": "ok",
    "initialised": "initialised (first run)",
    "fallback": "site blocked → Google News fallback",
    "error": "error",
}


# ------------------------------------------------------------------ disclosure

def ai_label(settings: dict) -> str:
    """Short label shown at the very top (Art. 50(5): at the latest at first exposure)."""
    return ("> **AI-generated report.** Selected, summarised and analysed automatically by an AI "
            "system, without human editorial review before publication. Verify every item against "
            "its linked source. See the notice at the end.")


def disclosure(settings: dict, models: set[str], link_stats: tuple[int, int], site_url: str | None,
               provider: str = "gemini") -> str:
    pub = settings.get("publisher", {})
    name = pub.get("name") or "RWE Regulatory Watch"
    contact = f" Contact: {pub['contact']}." if pub.get("contact") else ""
    model_txt = ", ".join(sorted(models)) if models else "none (raw list, no AI analysis this week)"
    ok, removed = link_stats
    repo = settings.get("tool", {}).get("repository_url")
    lines = [
        "---",
        "## About this report",
        "",
        "**AI-generated content — transparency notice (EU AI Act, Regulation (EU) 2024/1689, Article 50(4)).** "
        "This text was generated by an artificial-intelligence system and published without prior human "
        "editorial review. It is disclosed as artificially generated.",
        "",
        "- **How it is produced:** items are collected automatically from public sources (regulatory "
        "agencies, HTA bodies, EUR-Lex, Federal Register, PubMed, Europe PMC, Crossref, arXiv, "
        "ClinicalTrials.gov, Google News). An AI model then scores their relevance, selects the most "
        "substantial ones and writes the summaries and analyses.",
        (f"- **AI system:** Google Gemini via the free tier of the Gemini API (model(s) used this week: "
         f"{model_txt}). The pipeline runs on GitHub Actions" if provider == "gemini" else
         f"- **AI system:** Anthropic Claude via the Anthropic API (model(s) used this week: "
         f"{model_txt}). The pipeline runs on GitHub Actions")
        + (" and is published with GitHub Pages." if site_url else "."),
        "- **Verification needed:** AI output can contain errors, omissions, misattributions or "
        "over-interpretation. Always check the linked primary source before relying on, citing or "
        "reusing any item. Press items are secondary sources; preprints are not peer reviewed.",
        f"- **Automatic safeguards:** the model only receives collected items; every link in this report "
        f"was checked against the collected sources ({ok} verified, {removed} removed).",
        "- **Not advice:** this report is for information only and is not legal, regulatory, medical "
        "or investment advice.",
        f"- **Publisher:** {name} (automated publication).{contact}",
        "- **Licence:** this report may be shared and downloaded unmodified, with attribution, under "
        f"[CC BY-ND 4.0](https://creativecommons.org/licenses/by-nd/4.0/), attribution: {name}."
        + (f" The tool's source code: {repo} (no-derivatives licence)." if repo else ""),
    ]
    if site_url:
        lines.append(f"- **Archive & RSS:** {site_url}")
    return "\n".join(lines)


# -------------------------------------------------------------------- coverage

def _sorted(statuses):
    by_region = defaultdict(list)
    for s in statuses:
        by_region[s["region"]].append(s)
    for region in REGION_ORDER + sorted(set(by_region) - set(REGION_ORDER)):
        for s in sorted(by_region.get(region, []), key=lambda x: (x["tier"], x["name"])):
            yield region, s


def _row(region, s):
    status = STATUS_LABEL.get(s["status"], s["status"])
    if s["status"] in ("error", "fallback") and s.get("error"):
        status += f" ({s['error'][:40]})"
    return f"| {region} | {s['name']} | {'major' if s['tier'] == 1 else 'wider'} | {status} | {s['new']} |"


def coverage(statuses: list[dict], full: bool, site_url: str | None = None,
             alerts: list[str] | None = None) -> str:
    c = Counter(s["status"] for s in statuses)
    lines = ["## Coverage",
             f"{len(statuses)} sources · {c['ok'] + c['initialised']} read directly · "
             f"{c['fallback']} via Google News fallback · {c['error']} unreachable. "
             "*New* = never seen before and passed the relevance filter."]
    if alerts:
        lines.append("\n**⚠️ Source health alert:** " + "; ".join(alerts))
    rows = [(r, s) for r, s in _sorted(statuses) if full or s["status"] in ("error", "fallback")]
    if rows:
        if not full:
            lines.append("\nSources needing attention this week:")
        lines.append("\n| Region | Source | Tier | Status | New |\n|---|---|---|---|---|")
        lines += [_row(r, s) for r, s in rows]
    if not full and site_url:
        lines.append(f"\nFull coverage table: {site_url}")
    return "\n".join(lines)


TOPIC_TITLES = {"guidance": "Guidance & regulatory frameworks", "decision": "Regulatory & HTA decisions",
                "methods": "Methodology & scientific publications", "policy": "Policy & legislation",
                "data": "Data, infrastructure & governance", "global": "Global outlook", "other": "Other"}


def scored_digest(items: list[dict], reason: str) -> str:
    """Degraded mode when only the writing step failed: items ranked by AI triage score,
    grouped by topic, each with the one-line triage reason."""
    out = [f"> ⚠️ The AI writing step was unavailable this run ({reason}). Below are the items "
           "selected by the AI triage, ranked by relevance score (0–10) with a one-line reason. "
           "No summaries or analyses this time."]
    groups = defaultdict(list)
    for it in items:
        groups[it.get("topic") or "other"].append(it)
    for key in ["guidance", "decision", "policy", "methods", "data", "global", "other"]:
        group = sorted(groups.get(key, []), key=lambda x: -x.get("score", 0))
        if not group:
            continue
        out.append(f"\n## {TOPIC_TITLES[key]}")
        for it in group:
            tag = {"press": " · press (secondary source)", "preprint": " · preprint",
                   "registry": " · registry entry"}.get(it["kind"], "")
            pub = f" — {it['publisher']}" if it.get("publisher") else ""
            date = f", {it['date']}" if it.get("date") else ""
            why = f" — *{it['triage_reason']}*" if it.get("triage_reason") else ""
            out.append(f"- **[{it['title']}]({it['url']})**{pub} ({it['source']}{date}{tag}) "
                       f"· score {it.get('score', 0):g}{why}")
    return "\n".join(out)


def raw_digest(items: list[dict]) -> str:
    if not items:
        return "No new items passed the filters this week."
    out = ["*Raw list (automatic analysis unavailable) — detected items, grouped by region.*"]
    by_region = defaultdict(list)
    for it in items:
        by_region[it["region"]].append(it)
    for region in REGION_ORDER + sorted(set(by_region) - set(REGION_ORDER)):
        group = by_region.get(region)
        if not group:
            continue
        out.append(f"\n## {region}")
        for it in group:
            date = f" ({it['date']})" if it.get("date") else ""
            pub = f" — {it['publisher']}" if it.get("publisher") else ""
            out.append(f"- **{it['source']}** — [{it['title']}]({it['url']}){pub}{date}")
    return "\n".join(out)


