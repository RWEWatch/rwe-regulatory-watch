AI_META = ('<meta name="ai-generated" content="true">'
           '<meta name="generator" content="RWE Regulatory Watch (Google Gemini API, GitHub Actions)">')


def to_html(title: str, body_md: str, meta: str, nav: str = "") -> str:
    html_body = md.markdown(body_md, extensions=["tables", "sane_lists"])
    return (f"<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>"
            f"<meta name='viewport' content='width=device-width,initial-scale=1'>{AI_META}"
            f"<title>{title}</title><style>{CSS}</style></head>"
            f"<body>{nav}<h1>{title}</h1><p class='meta'>{meta}</p>{html_body}</body></html>")
